/** Mongolian Cyrillic → Latin, the way people spell their names in email addresses. */
export function transliterate(text: string): string {
  let out = '';
  // "Оюун" is spelled "Oyun", not "Oyuun".
  for (const ch of text.replace(/юу/g, 'ю').replace(/ЮУ/g, 'Ю')) {
    const lower = ch.toLowerCase();
    const latin = LATIN[lower];
    if (latin === undefined) out += ch;
    else out += ch === lower ? latin : latin.charAt(0).toUpperCase() + latin.slice(1);
  }
  return out;
}

/** "Бат-Эрдэнэ Ганболд" → "baterdene.g" */
export function emailLocalFor(name: string): string {
  const [given = '', family = ''] = transliterate(name).toLowerCase().split(/\s+/);
  const clean = (s: string) => s.replace(/[^a-z]/g, '');
  return family ? `${clean(given)}.${clean(family).charAt(0)}` : clean(given);
}

